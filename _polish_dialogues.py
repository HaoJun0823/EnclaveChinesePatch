# ============ 3. 主流程：按中英文件逐条对应 ============
def process_file(fname):
    with open(EN_DIR + fname, 'rb') as f:
        en_text = f.read().decode('utf-16')
    with open(SRC_DIR + fname, 'rb') as f:
        cn_text = f.read().decode('utf-16')

    # 分别提取 TEXT 内容（顺序对应）
    en_texts = re.findall(r'\*TEXT "(.*?)"', en_text)
    cn_texts = re.findall(r'\*TEXT "(.*?)"', cn_text)
    assert len(en_texts) == len(cn_texts), f'{fname}: 中英 TEXT 数不一致 {len(en_texts)} vs {len(cn_texts)}'

    # 建立 中文原文 -> 新中文 映射
    cn_to_new = {}
    for en_v, cn_v in zip(en_texts, cn_texts):
        if en_v in MANUAL:
            cn_to_new[cn_v] = MANUAL[en_v]
        else:
            cn_to_new[cn_v] = apply_terms(cn_v)

    # 按顺序替换中文文件中的 TEXT（注意可能有重复的中文原文，需要按序消费）
    def repl(m):
        # 每遇到一个 TEXT 就消费一个 cn_texts
        idx = repl.counter
        repl.counter += 1
        if idx < len(cn_texts):
            new_val = cn_to_new.get(cn_texts[idx], apply_terms(m.group(1)))
            return f'*TEXT "{new_val}"'
        return m.group(0)
    repl.counter = 0

    new_text = re.sub(r'\*TEXT "(.*?)"', repl, cn_text)
    return new_text

def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    files = sorted([f for f in os.listdir(SRC_DIR) if f.endswith('.xrg')])
    for f in files:
        new_text = process_file(f)
        with open(OUT_DIR + f, 'wb') as fh:
            fh.write(new_text.encode('utf-16'))
        print(f'处理: {f}')
    print(f'完成 -> {OUT_DIR}')

if __name__ == '__main__':
    main()
