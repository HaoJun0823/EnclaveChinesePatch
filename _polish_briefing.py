FIGHT_KEYS = ['BRIEFING_D_C1_1','BRIEFING_D_C1_2','BRIEFING_D_C3_1','BRIEFING_L_C1_1','BRIEFING_L_C1_2','BRIEFING_L_C3_1','BRIEFING_L_C3_2']
BEWARE_KEYS = ['BRIEFING_D_C1_3','BRIEFING_D_C3_3','BRIEFING_L_C1_3','BRIEFING_L_C3_3']

def main():
    raw = open(ST_PATH,'rb').read()
    text = raw.decode('utf-16-le')
    if text.startswith('\ufeff'): text = text[1:]
    lines = text.split('\n')
    replaced = 0
    for i, line in enumerate(lines):
        m = re.match(r'^(\t\*([A-Za-z0-9_]+)[ \t]+")[^"]*(")$', line.rstrip('\r'))
        if not m: continue
        key = m.group(2)
        if key in NEW and NEW[key] is not None:
            lines[i] = m.group(1) + NEW[key] + m.group(3) + ('\r' if line.endswith('\r') else '')
            replaced += 1
        elif key in FIGHT_KEYS:
            lines[i] = m.group(1) + FIGHT + m.group(3) + ('\r' if line.endswith('\r') else '')
            replaced += 1
        elif key in BEWARE_KEYS:
            lines[i] = m.group(1) + BEWARE + m.group(3) + ('\r' if line.endswith('\r') else '')
            replaced += 1
    out = ('\ufeff' if raw[:2]==b'\xff\xfe' else '') + '\n'.join(lines)
    open(ST_PATH,'wb').write(out.encode('utf-16-le'))
    print(f"已替换 {replaced} 个 key（目标 43）")

if __name__ == '__main__':
    main()
